//! Runs the legacy batch indicators on fixed inputs and writes their (trimmed) outputs.
//! See Cargo.toml for how to run it. Deterministic: rerunning gives identical bytes.

use qcharts_core::indicator::{bollinger, ema, macd, rsi, sma};
use serde_json::{json, Map, Value};

struct Lcg(u64);
impl Lcg {
    fn unit(&mut self) -> f64 {
        self.0 = self
            .0
            .wrapping_mul(6_364_136_223_846_793_005)
            .wrapping_add(1_442_695_040_888_963_407);
        f64::from((self.0 >> 32) as u32) / 2_147_483_648.0 - 1.0
    }
}

fn round2(x: f64) -> f64 {
    (x * 100.0).round() / 100.0
}

fn walk(n: usize, seed: u64, start: f64, step: f64) -> Vec<f64> {
    let mut r = Lcg(seed);
    let mut x = start;
    (0..n)
        .map(|_| {
            x = round2(x * (1.0 + step * r.unit()));
            x
        })
        .collect()
}

fn main() {
    let root = std::path::Path::new(env!("CARGO_MANIFEST_DIR")).join("../..");
    let sample: Value = serde_json::from_str(
        &std::fs::read_to_string(root.join("fixtures/bars/sample.json")).unwrap(),
    )
    .unwrap();
    let sample_close: Vec<f64> = sample["data"]["bars"]
        .as_array()
        .unwrap()
        .iter()
        .map(|b| b["c"].as_f64().unwrap())
        .collect();
    let mut flat = vec![50.0; 20];
    flat.extend([50.5, 50.0, 49.5, 49.5, 49.5, 50.0, 51.0, 51.0, 50.0, 50.0]);
    flat.extend(vec![48.0; 10]);

    let inputs: Vec<(&str, Vec<f64>)> = vec![
        ("sample_close", sample_close),
        ("walk", walk(500, 42, 100.0, 0.02)),
        ("high_level", walk(500, 7, 10_000.0, 0.002)),
        ("flat", flat),
    ];

    let mut cases = Vec::new();
    for (name, x) in &inputs {
        for p in [1usize, 2, 5, 20] {
            let out = sma::calculate(x, p).unwrap();
            cases.push(json!({"input": name, "study": "sma", "params": {"period": p}, "outputs": {"sma": out}}));
        }
        for p in [1usize, 2, 9, 20] {
            let out = ema::calculate(x, p).unwrap();
            cases.push(json!({"input": name, "study": "ema", "params": {"period": p}, "outputs": {"ema": out}}));
        }
        for p in [1usize, 2, 14] {
            let out = rsi::calculate(x, p).unwrap();
            cases.push(json!({"input": name, "study": "rsi", "params": {"period": p}, "outputs": {"rsi": out}}));
        }
        for (f, s, g) in [(12usize, 26usize, 9usize), (2, 3, 1), (3, 10, 4)] {
            let o = macd::MACD::new(f, s, g).unwrap().calculate_full(x).unwrap();
            cases.push(json!({"input": name, "study": "macd", "params": {"fast": f, "slow": s, "signal": g},
                "outputs": {"macd": o.macd_line, "signal": o.signal_line, "histogram": o.histogram}}));
        }
        for (p, k) in [(20usize, 2.0f64), (1, 2.0), (5, 1.5)] {
            let o = bollinger::BollingerBands::new(p, k).unwrap().calculate_full(x).unwrap();
            cases.push(json!({"input": name, "study": "bollinger", "params": {"period": p, "k": k},
                "outputs": {"middle": o.middle, "upper": o.upper, "lower": o.lower, "bandwidth": o.bandwidth}}));
        }
    }
    let mut inp = Map::new();
    for (name, x) in inputs {
        inp.insert(name.to_owned(), json!(x));
    }
    let doc = json!({
        "note": "Legacy Q-Charts batch indicator outputs (trimmed: no warmup values, aligned to the last bar). Generated by tools/legacy-oracle; do not edit.",
        "inputs": inp,
        "cases": cases,
    });
    let mut text = serde_json::to_string(&doc).unwrap();
    text.push('\n');
    let out = root.join("fixtures/oracle/legacy_indicators.json");
    std::fs::write(&out, text).unwrap();
    println!("wrote {}", out.display());
}
