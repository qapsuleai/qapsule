#!/usr/bin/env bash
# RD2 M2/M3 (chart) — inputs of the chart surface mockups, written OUTSIDE this folder
# (default: the git-ignored gallery output). Nothing here is product code.
#
#   docs/design/mockups/surfaces/chart/render.sh [OUT]
#
# OUT/vars/      <look>-<theme>.css (`qp look css`) and fonts-<look>.css  → page `&vars=`
# OUT/charts/<look>-<theme>/<slot>.png  core charts (`qp render`, DPR 2 desktop, 3 phone)
#                                        → page `&charts=`
# Slot sizes are the frame geometry of the pages (chart.css); a page shows each image at
# exactly that CSS size (frame.js srcset `<dpr>x`, object-fit none).
set -euo pipefail
ROOT=$(git -C "$(dirname "$0")" rev-parse --show-toplevel)
MAIN=$(dirname "$(git -C "$ROOT" rev-parse --path-format=absolute --git-common-dir)")
QP="${CARGO_TARGET_DIR:-$MAIN/target}/debug/qp"
OUT=${1:-$ROOT/rounds/RD2/experiments/gallery/out/surfaces/chart}
FX=fixtures/design/desk.json
cd "$ROOT"
mkdir -p "$OUT/vars"

fonts() { # every font file of the look under its CSS family (as scripts/design-gallery does)
  "$QP" look show "$1" | python3 -c '
import json, sys, pathlib
root = pathlib.Path(sys.argv[1]) / "crates/qp-render/assets/fonts"
fs = json.load(sys.stdin).get("fonts") or []
seen = []
for f in fs:
    for g in [x for x in fs if x["family"] == f["family"]]:
        s = "@font-face { font-family: \"%s\"; src: url(\"%s\"); font-weight: %s; font-style: %s; }" % (
            f["css_family"], (root / g["file"]).as_uri(), g["weight"], "italic" if g.get("italic") else "normal")
        if s not in seen: seen.append(s)
print("\n".join(seen))' "$ROOT" > "$OUT/vars/fonts-$1.css"
}

render() { # look theme dpr slot w h [cursor]
  local dir="$OUT/charts/$1-$2"; mkdir -p "$dir"
  "$QP" render --transcript "$FX" --view desk --look "$1" --theme "$2" --scale "$3" \
    --width "$5" --height "$6" ${7:+--cursor "$7"} -o "$dir/$4.png"
}

for look in tavek tavek-tel; do
  fonts "$look"
  for theme in dark light; do
    { echo "/* generated by render.sh from \`qp look css $look --theme $theme\`; do not edit */"
      echo ":root {"; "$QP" look css "$look" --theme "$theme"; echo "}"; } > "$OUT/vars/$look-$theme.css"
  done
done

for theme in dark light; do
  # Desktop (`tavek`, DPR 2): hero cell 900×540, state cell 600×380; `cell-cur` = crosshair on
  # bar 182 (15 Eyl, the third bar after the break).
  render tavek "$theme" 2 hero 900 540
  render tavek "$theme" 2 cell 600 380
  render tavek "$theme" 2 cell-cur 600 380 182
  # Phone (`tavek-tel`, DPR 3): state chart 390×300, full-screen chart 390×340.
  render tavek-tel "$theme" 3 tel 390 300
  render tavek-tel "$theme" 3 tel-cur 390 300 182
  render tavek-tel "$theme" 3 tel-hero 390 340
  # Phone held sideways (Y27 "Yatay kip"): crosshair and the full OHLC legend.
  render tavek-tel "$theme" 3 tel-land 760 300 182
done
echo "$OUT"
