//! Regenerates `src/tzdata.rs` from jiff's bundled tzdb (jiff-tzdb, pinned in Cargo.lock).
//!
//! ```sh
//! cargo run -p qp-calendar --example gen_tzdata
//! ```
//! `tests/tzdata.rs` checks the committed table against jiff, so a stale table fails CI.

use std::fmt::Write as _;

use jiff::Timestamp;

/// Zones embedded in the core. Add a zone here when a calendar needs it.
const ZONES: [&str; 2] = ["America/New_York", "Europe/Istanbul"];
/// Covered range: [1900-01-01, 2100-01-01) UTC.
const FROM_S: i64 = -2_208_988_800;
const TO_S: i64 = 4_102_444_800;

fn main() -> Result<(), Box<dyn std::error::Error>> {
    let mut s = String::new();
    writeln!(
        s,
        "//! Generated by `cargo run -p qp-calendar --example gen_tzdata` from jiff's bundled"
    )?;
    writeln!(
        s,
        "//! tzdb (jiff-tzdb, pinned in Cargo.lock). Do not edit. UTC offset transitions in"
    )?;
    writeln!(
        s,
        "//! [1900-01-01, 2100-01-01): `(utc_second, offset_seconds_from_then_on)`."
    )?;
    writeln!(s)?;
    writeln!(s, "use crate::zone::ZoneData;")?;
    writeln!(s)?;
    writeln!(s, "pub(crate) static ZONES: &[ZoneData] = &[")?;
    for name in ZONES {
        let tz = jiff::tz::db().get(name)?;
        let start = Timestamp::from_second(FROM_S)?;
        let initial = tz.to_offset(start).seconds();
        writeln!(s, "    ZoneData {{")?;
        writeln!(s, "        name: {name:?},")?;
        writeln!(s, "        initial: {initial},")?;
        writeln!(s, "        transitions: &[")?;
        for tr in tz.following(start) {
            let t = tr.timestamp().as_second();
            if t >= TO_S {
                break;
            }
            writeln!(s, "            ({t}, {}),", tr.offset().seconds())?;
        }
        writeln!(s, "        ],")?;
        writeln!(s, "    }},")?;
    }
    writeln!(s, "];")?;
    let out = std::path::Path::new(env!("CARGO_MANIFEST_DIR")).join("src/tzdata.rs");
    std::fs::write(&out, s)?;
    println!("wrote {}", out.display());
    Ok(())
}
