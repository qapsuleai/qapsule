//! Generates Rust types from the byte-exact Matriks protos in `proto/` (K62).
//!
//! `protox` (pure Rust protobuf compiler) parses the protos into a
//! `FileDescriptorSet`; `prost-build` turns that into Rust code. No `protoc`
//! is needed on the machine. The proto files are never edited; any naming
//! issue is handled here.
//!
//! Besides the prost types (`messages.rs`), this script emits `fields.rs`:
//! a table of (field number, proto field name) per message, taken from the
//! same descriptors, so the decoders can report which fields arrived by name
//! without a hand-written list.

use std::fmt::Write as _;
use std::path::PathBuf;

fn main() {
    let manifest = PathBuf::from(std::env::var_os("CARGO_MANIFEST_DIR").expect("manifest dir"));
    let proto_dir = manifest.join("proto");
    println!("cargo:rerun-if-changed=proto");

    let mut files: Vec<String> = std::fs::read_dir(&proto_dir)
        .expect("read proto dir")
        .filter_map(|e| {
            let name = e.ok()?.file_name().into_string().ok()?;
            name.ends_with(".proto").then_some(name)
        })
        .collect();
    files.sort();
    for f in &files {
        println!("cargo:rerun-if-changed=proto/{f}");
    }

    let fds = protox::compile(&files, [&proto_dir]).expect("protox: compile Matriks protos");

    let out_dir = PathBuf::from(std::env::var_os("OUT_DIR").expect("OUT_DIR"));
    std::fs::write(out_dir.join("fields.rs"), field_table(&fds)).expect("write fields.rs");

    prost_build::Config::new()
        .compile_fds(fds)
        .expect("prost-build: generate Matriks types");
}

/// Emits `pub const MESSAGE_FIELDS: &[MessageFields]` for every message
/// (nested ones included), sorted by full name; fields sorted by number.
fn field_table(fds: &prost_types::FileDescriptorSet) -> String {
    fn walk(
        prefix: &str,
        msg: &prost_types::DescriptorProto,
        out: &mut Vec<(String, Vec<(i32, String)>)>,
    ) {
        let full = format!("{prefix}.{}", msg.name());
        let mut fields: Vec<(i32, String)> = msg
            .field
            .iter()
            .map(|f| (f.number(), f.name().to_string()))
            .collect();
        fields.sort();
        for nested in &msg.nested_type {
            walk(&full, nested, out);
        }
        out.push((full, fields));
    }
    let mut all = Vec::new();
    for file in &fds.file {
        let prefix = file.package().to_string();
        for msg in &file.message_type {
            walk(&prefix, msg, &mut all);
        }
    }
    all.sort();
    let mut s =
        String::from("// @generated by qp-matriks build.rs from proto/*.proto. Do not edit.\n");
    s.push_str("/// Every message declared in `proto/*.proto` (nested ones included), sorted by full name.\n");
    s.push_str("pub const MESSAGE_FIELDS: &[MessageFields] = &[\n");
    for (name, fields) in &all {
        let _ = writeln!(s, "    MessageFields {{ message: {name:?}, fields: &[");
        for (n, f) in fields {
            let _ = writeln!(s, "        ({n}, {f:?}),");
        }
        s.push_str("    ] },\n");
    }
    s.push_str("];\n");
    s
}
